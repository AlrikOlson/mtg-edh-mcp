/** Lowercased keyword label -> owning batch chunk; built once. */
export function keywordBatchIndex(): ReadonlyMap<string, string> {
  const map = new Map<string, string>();
  for (const batch of KEYWORD_BATCHES) {
    for (const keyword of batch.keywords) map.set(keyword.toLowerCase(), batch.chunk);
  }
  return map;
}
